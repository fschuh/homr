#: An eighth rising from the head, a 16th falling from it.
EIGHTH_OVER_16TH = SharedNoteheadReading("eighth", "16th", None, "two_stems")

GRAND_STAFF = [
    "clef_G2 _ _ _ _ upper&clef_F4 _ _ _ _ lower",
    "keySignature_0 . . . . .",
]


def butterfly_bar(first: str, second: str) -> list[str]:
    """A 2/4 bar of Chopin's Op. 25 No. 9: each beat's eighth shares its head with the first
    of four 16ths, over left-hand eighths. The transformer reads only the eighth."""
    return [
        f"note_8 {first} _ _ _ upper&note_8 G2 _ _ _ lower",
        "note_16 G5 _ _ _ upper",
        "note_16 C6 _ _ _ upper&note_8 D3 _ _ _ lower",
        "note_16 C5 _ _ _ upper",
        f"note_8 {second} _ _ _ upper&note_8 F2 _ _ _ lower",
        "note_16 A5 _ _ _ upper",
        "note_16 E6 _ _ _ upper&note_8 A3 _ _ _ lower",
        "note_16 D6 _ _ _ upper",
        "barline . . . . .",
    ]


#: A 2/4 bar the transformer reads right.
CLEAN_BAR = ["note_8 E5 _ _ _ upper&note_8 C3 _ _ _ lower"] * 4 + ["barline . . . . ."]

#: Where the notes of ``butterfly_bar`` start, in quarter notes, once repaired.
BUTTERFLY_ONSETS = sorted(
    [
        ("1", "B4", 0.0),
        ("1", "G5", 0.25),
        ("1", "C6", 0.5),
        ("1", "C5", 0.75),
        ("1", "D5", 1.0),
        ("1", "A5", 1.25),
        ("1", "E6", 1.5),
        ("1", "D6", 1.75),
        ("2", "G2", 0.0),
        ("2", "D3", 0.5),
        ("2", "F2", 1.0),
        ("2", "A3", 1.5),
    ]
)


def six_eight_bar(first: str | None, second: str | None) -> list[str]:
    """A 6/8 bar: each half an eighth sharing its head with the first of six 16ths over a
    dotted quarter, or, without a shared pitch, two dotted quarters read right."""
    if first is None or second is None:
        return ["note_4. E5 _ _ _ upper&note_4. C3 _ _ _ lower"] * 2 + ["barline . . . . ."]
    lines = []
    for pitch in (first, second):
        lines.append(f"note_8 {pitch} _ _ _ upper&note_4. C3 _ _ _ lower")
        lines.extend(["note_16 E5 _ _ _ upper"] * 5)
    return [*lines, "barline . . . . ."]


def identity_transform() -> PredictionCoordinateTransform:
    return PredictionCoordinateTransform(
        source_image_size=(600, 400),
        autocrop_box=(0, 0, 600, 400),
        cropped_size=(600, 400),
        resized_size=(600, 400),
        resize_scale=(1.0, 1.0),
        prediction_size=(600, 400),
    )


class StubbedSidecar(VisualSidecarBuilder):
    """A sidecar whose shared-notehead readings are given by pitch, noting what was read."""

    def __init__(self, readings: dict[str, SharedNoteheadReading] | None = None) -> None:
        super().__init__(identity_transform())
        self.readings = readings or {}
        self.read: list[str] = []

    def read_shared_notehead(self, symbol: EncodedSymbol) -> SharedNoteheadReading | None:
        self.read.append(symbol.pitch)
        return self.readings.get(symbol.pitch)


def tokens(lines: list[str]) -> list[EncodedSymbol]:
    return read_token_lines(lines)


def write(
    lines: list[str],
    sidecar: VisualSidecarBuilder | None,
    repair: bool = True,
) -> Any:
    args = XmlGeneratorArguments(repair_shared_notehead_timing=repair)
    return generate_xml(args, [tokens(lines)], "", visual_sidecar=sidecar)


def measure_onsets(xml: Any, index: int = 0) -> list[tuple[str, str, float]]:
    """(staff, pitch, onset in quarter notes) for every pitched note of one measure."""
    root = ET.fromstring(xml.to_string())  # noqa: S314 - generated by the test itself
    part = root.find("part")
    assert part is not None
    divisions = int(part.findtext("measure/attributes/divisions", "1"))
    measure = part.findall("measure")[index]
    time, onset, result = 0, 0, []
    for element in measure:
        if element.tag == "backup":
            time -= int(element.findtext("duration", "0"))
        elif element.tag == "forward":
            time += int(element.findtext("duration", "0"))
        elif element.tag == "note":
            if element.find("chord") is None:
                onset = time
                time += int(element.findtext("duration", "0"))
            pitch = element.find("pitch")
            if pitch is not None:
                name = pitch.findtext("step", "") + pitch.findtext("octave", "")
                result.append((element.findtext("staff", "1"), name, onset / divisions))
    return sorted(result)


def time_signatures(xml: Any) -> list[tuple[str | None, str | None]]:
    root = ET.fromstring(xml.to_string())  # noqa: S314 - generated by the test itself
    return [(t.findtext("beats"), t.findtext("beat-type")) for t in root.iter("time")]


def outcomes(sidecar: VisualSidecarBuilder) -> list[tuple[str, str, str, str | None]]:
    return [
        (record.symbol.pitch, record.status, record.reason, record.next_notes_after)
        for _visual_id, record in sidecar.state.shared_notehead_records
    ]


class TestCandidate(unittest.TestCase):
    def candidate(
        self, rhythm: str, up: str | None, down: str | None, dotted: bool | None = None
    ) -> tuple[Fraction | None, str]:
        reading = SharedNoteheadReading(up, down, dotted, "two_stems")
        return shared_notehead_candidate(EncodedSymbol(rhythm, "C5"), reading)

    def test_the_shorter_printed_value_ends_the_moment(self) -> None:
        self.assertEqual(self.candidate("note_8", "eighth", "16th"), (Fraction(1, 16), ""))
        self.assertEqual(self.candidate("note_4", "16th", "quarter"), (Fraction(1, 16), ""))

    def test_one_unread_value_leaves_the_other_to_decide(self) -> None:
        self.assertEqual(self.candidate("note_8", None, "16th"), (Fraction(1, 16), ""))
        self.assertEqual(self.candidate("note_8", "16th", None), (Fraction(1, 16), ""))

    def test_a_token_matching_neither_stem_is_not_repaired(self) -> None:
        self.assertEqual(
            self.candidate("note_4", "eighth", "16th"), (None, "token_matches_neither")
        )

    def test_a_token_as_short_as_the_stems_needs_no_repair(self) -> None:
        self.assertEqual(self.candidate("note_16", "eighth", "16th"), (None, "token_is_shortest"))
        self.assertEqual(self.candidate("note_8", "eighth", None), (None, "token_is_shortest"))

    def test_only_plain_tokens_are_repaired(self) -> None:
        for rhythm in ("note_8.", "note_12", "note_8G", "rest_8"):
            self.assertEqual(self.candidate(rhythm, "eighth", "16th"), (None, "not_a_plain_note"))

    def test_a_dotted_head_is_not_repaired(self) -> None:
        self.assertEqual(self.candidate("note_8", "eighth", "16th", True), (None, "dotted"))

    def test_without_values_nothing_is_repaired(self) -> None:
        self.assertEqual(self.candidate("note_8", None, None), (None, "values_unclear"))


class TestTimingRepairs(unittest.TestCase):
    def test_notes_after_a_shared_head_start_when_its_shorter_voice_ends(self) -> None:
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *butterfly_bar("B4", "D5")]
        sidecar = StubbedSidecar({"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH})
        xml = write([*lines, *CLEAN_BAR], sidecar)
        self.assertEqual(measure_onsets(xml), BUTTERFLY_ONSETS)
        self.assertEqual(time_signatures(xml), [("2", "4")])
        self.assertEqual(
            outcomes(sidecar),
            [("B4", APPLIED, "bar_adds_up", "16th"), ("D5", APPLIED, "bar_adds_up", "16th")],
        )
        # The token keeps its value: no note is added and none changes.
        root = ET.fromstring(xml.to_string())  # noqa: S314 - generated by the test itself
        b4 = [n for n in root.iter("note") if n.findtext("pitch/step") == "B"][0]
        self.assertEqual(b4.findtext("type"), "eighth")
        self.assertEqual(len(list(root.iter("note"))), 20)

    def test_switched_off_the_bar_is_written_as_recognized(self) -> None:
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *butterfly_bar("B4", "D5"), *CLEAN_BAR]
        sidecar = StubbedSidecar({"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH})
        off = write(lines, sidecar, repair=False)
        unread = write(lines, StubbedSidecar())
        self.assertEqual(off.to_string(), unread.to_string())
        self.assertEqual(sidecar.read, [])
        self.assertIs(sidecar.state.timing_repairs_enabled, False)
        self.assertEqual(sidecar.state.shared_notehead_records, [])
        self.assertNotEqual(measure_onsets(off), BUTTERFLY_ONSETS)

    def test_without_shared_heads_the_writer_measures_as_before(self) -> None:
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *butterfly_bar("B4", "D5"), *CLEAN_BAR]
        groups = add_tuplet_start_stop(group_into_chords(tokens(lines)))
        for sidecar in (None, StubbedSidecar()):
            repairs = TimingRepairs(groups, sidecar)
            self.assertEqual(
                repairs.division_and_nominator(), find_division_and_time_signature_nominator(groups)
            )
            self.assertEqual(
                repairs.section_nominators(), time_signature_section_nominators(groups)
            )
            ends = [repairs.shared_notehead_ends(g, Fraction(0), part=1, measure=1) for g in groups]
            self.assertEqual(ends, [[]] * len(groups))

    def test_a_bar_that_already_adds_up_is_left_alone(self) -> None:
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *CLEAN_BAR, *CLEAN_BAR]
        sidecar = StubbedSidecar({"E5": EIGHTH_OVER_16TH})
        xml = write(lines, sidecar)
        self.assertEqual(xml.to_string(), write(lines, StubbedSidecar()).to_string())
        self.assertEqual({o[1:3] for o in outcomes(sidecar)}, {(DECLINED, "bar_already_adds_up")})

    def test_a_bar_the_repairs_do_not_balance_is_left_alone(self) -> None:
        # Only the first beat's shared head is read, so the bar still runs a 16th over.
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *butterfly_bar("B4", "D5"), *CLEAN_BAR]
        sidecar = StubbedSidecar({"B4": EIGHTH_OVER_16TH})
        xml = write(lines, sidecar)
        self.assertEqual(xml.to_string(), write(lines, StubbedSidecar()).to_string())
        self.assertEqual(outcomes(sidecar), [("B4", DECLINED, "bar_still_does_not_add_up", "16th")])

    def test_without_a_bar_length_nothing_is_repaired(self) -> None:
        # No time signature, and the only bar is nine 16ths long: no meter has that bar.
        bar = butterfly_bar("B4", "D5")
        bar[0] = "note_16 B4 _ _ _ upper&note_8 G2 _ _ _ lower"  # the first beat read right
        sidecar = StubbedSidecar({"D5": EIGHTH_OVER_16TH})
        write([*GRAND_STAFF, *bar], sidecar)
        self.assertEqual(outcomes(sidecar), [("D5", DECLINED, "no_bar_length", "16th")])

    def test_the_repairs_set_the_typical_bar_only_where_an_unrepaired_bar_has_it(self) -> None:
        # Without a time signature the bar length is the typical bar, which the misread
        # bars make five eighths long. One bar read right confirms the repaired length.
        broken = butterfly_bar("B4", "D5") * 3
        readings = {"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH}
        confirmed = StubbedSidecar(readings)
        xml = write([*GRAND_STAFF, *broken, *CLEAN_BAR], confirmed)
        self.assertEqual({o[1] for o in outcomes(confirmed)}, {APPLIED})
        self.assertEqual(measure_onsets(xml, 2), BUTTERFLY_ONSETS)

        unconfirmed = StubbedSidecar(readings)
        write([*GRAND_STAFF, *broken, *butterfly_bar("B4", "D5")], unconfirmed)
        self.assertEqual(
            {o[1:3] for o in outcomes(unconfirmed)}, {(DECLINED, "bar_already_adds_up")}
        )

    def test_the_repairs_set_a_sections_beat_count_only_where_an_unrepaired_bar_has_it(
        self,
    ) -> None:
        readings = {"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH}
        broken = six_eight_bar("B4", "D5") * 3
        header = [*GRAND_STAFF, "timeSignature/8 . . . . ."]

        confirmed = StubbedSidecar(readings)
        xml = write([*header, *broken, *six_eight_bar(None, None)], confirmed)
        self.assertEqual(time_signatures(xml), [("6", "8")])
        self.assertEqual({o[1] for o in outcomes(confirmed)}, {APPLIED})

        unconfirmed = StubbedSidecar(readings)
        xml = write([*header, *broken, *six_eight_bar("B4", "D5")], unconfirmed)
        self.assertEqual(time_signatures(xml), [("7", "8")])
        self.assertEqual(
            {o[1:3] for o in outcomes(unconfirmed)}, {(DECLINED, "bar_already_adds_up")}
        )

    def test_a_bar_must_add_up_to_its_written_time_signature(self) -> None:
        # As on the Butterfly's first page every bar is misread, so the typical bar is
        # five eighths; the time signature written from it holds two quarters.
        lines = [
            *GRAND_STAFF,
            "timeSignature/4 . . . . .",
            *butterfly_bar("B4", "D5"),
            *butterfly_bar("A4", "C5"),
        ]
        sidecar = StubbedSidecar({"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH})
        xml = write(lines, sidecar)
        self.assertEqual(time_signatures(xml), [("2", "4")])
        self.assertEqual({o[1:3] for o in outcomes(sidecar)}, {(APPLIED, "bar_adds_up")})
        self.assertEqual(measure_onsets(xml), BUTTERFLY_ONSETS)

    def test_a_typical_bar_only_the_candidates_make_is_not_written_without_repairs(
        self,
    ) -> None:
        # The candidates move the typical bar from 19/32 to 9/16, a length one unrepaired
        # bar has; but no meter has a 9/16 bar without a time signature, so none applies.
        nine_16ths = butterfly_bar("A4", "C5")
        nine_16ths[0] = "note_16 A4 _ _ _ upper&note_8 G2 _ _ _ lower"
        lines = [
            *GRAND_STAFF,
            *CLEAN_BAR,
            *nine_16ths,
            *butterfly_bar("B4", "D5"),
            *butterfly_bar("B4", "D5"),
        ]
        groups = add_tuplet_start_stop(group_into_chords(tokens(lines)))
        sidecar = StubbedSidecar({"B4": EIGHTH_OVER_16TH})
        repairs = TimingRepairs(groups, sidecar)
        self.assertEqual(
            repairs.division_and_nominator(), find_division_and_time_signature_nominator(groups)
        )
        self.assertEqual(repairs.division_and_nominator()[1], Fraction(19, 32))
        for group in groups:
            repairs.shared_notehead_ends(group, Fraction(0), part=1, measure=1)
        self.assertEqual({o[1:3] for o in outcomes(sidecar)}, {(DECLINED, "no_bar_length")})

    def test_divisions_express_where_the_lost_note_ends(self) -> None:
        # A quarter shares its head with a lost 16th, and no token is shorter than an
        # eighth: the lower voice's eighths start between the eighths' own grid.
        lines = [
            *GRAND_STAFF,
            "timeSignature/4 . . . . .",
            "note_4 C5 _ _ _ upper&note_2 C3 _ _ _ lower",
            "note_8 D5 _ _ _ upper",
            "note_8 E5 _ _ _ upper",
            "note_4 G5 _ _ _ upper",
            "note_8 F5 _ _ _ upper",
            "barline . . . . .",
            *CLEAN_BAR,
            *CLEAN_BAR,
        ]
        sidecar = StubbedSidecar(
            {"C5": SharedNoteheadReading("16th", "quarter", None, "two_stems")}
        )
        xml = write(lines, sidecar)
        self.assertEqual(outcomes(sidecar), [("C5", APPLIED, "bar_adds_up", "16th")])
        root = ET.fromstring(xml.to_string())  # noqa: S314 - generated by the test itself
        self.assertEqual(root.findtext("part/measure/attributes/divisions"), "4")
        self.assertEqual(
            measure_onsets(xml),
            sorted(
                [
                    ("1", "C5", 0.0),
                    ("1", "D5", 0.25),
                    ("1", "E5", 0.75),
                    ("1", "G5", 1.0),
                    ("1", "F5", 1.25),
                    ("2", "C3", 0.0),
                ]
            ),
        )

    def test_only_a_head_alone_on_its_staff_at_its_moment_is_read(self) -> None:
        lines = [
            *GRAND_STAFF,
            "timeSignature/4 . . . . .",
            "note_4 B4 _ _ _ upper&note_4 D5 _ _ _ upper&note_4 G2 _ _ _ lower",
            "note_4 C5 _ _ _ upper&note_4 C3 _ _ _ lower",
            "barline . . . . .",
        ]
        sidecar = StubbedSidecar()
        write(lines, sidecar)
        self.assertEqual(sidecar.read, ["G2", "C5", "C3"])

    def test_each_shared_head_is_recorded_once_with_what_became_of_it(self) -> None:
        lines = [
            *GRAND_STAFF,
            "timeSignature/4 . . . . .",
            *butterfly_bar("B4", "D5"),
            *CLEAN_BAR,
            *butterfly_bar("B5", "F5"),
        ]
        sidecar = StubbedSidecar(
            {
                "B4": EIGHTH_OVER_16TH,
                "D5": EIGHTH_OVER_16TH,
                "G5": EIGHTH_OVER_16TH,  # a 16th token: nothing shorter to start after
                "B5": SharedNoteheadReading("quarter", "16th", None, "two_stems"),
                "F5": SharedNoteheadReading("eighth", "16th", None, "stem_unclear"),
            }
        )
        write(lines, sidecar)
        self.assertEqual(
            [
                (r.symbol.pitch, r.measure, r.status, r.reason)
                for _visual_id, r in sidecar.state.shared_notehead_records
            ],
            [
                ("B4", 1, APPLIED, "bar_adds_up"),
                ("G5", 1, NOT_NEEDED, "token_is_shortest"),
                ("D5", 1, APPLIED, "bar_adds_up"),
                ("B5", 3, DECLINED, "token_matches_neither"),
                ("G5", 3, NOT_NEEDED, "token_is_shortest"),
            ],
        )

    def test_the_sidecar_reports_each_shared_head_by_its_musicxml_id(self) -> None:
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *butterfly_bar("B4", "D5"), *CLEAN_BAR]
        voice = tokens(lines)
        b4 = next(symbol for symbol in voice if symbol.pitch == "B4")
        sidecar = StubbedSidecar({"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH})
        sidecar.visual_groups["vnote-1"] = linked_group("vnote-1")
        sidecar.matches_by_symbol_id[b4.visual_match_id] = VisualMatch(
            b4, "vnote-1", 0.9, "structural"
        )
        generate_xml(XmlGeneratorArguments(), [voice], "", visual_sidecar=sidecar)
        block = json.loads(json.dumps(sidecar.to_json_dict()))["timing_repairs"]
        self.assertEqual((block["version"], block["enabled"]), (1, True))
        self.assertEqual(
            block["shared_noteheads"][0],
            {
                "musicxml_id": "homr-note-1",
                "visual_group_id": "vnote-1",
                "part": 1,
                "measure": 1,
                "recognized": "note_8",
                "printed_up": "eighth",
                "printed_down": "16th",
                "dotted": None,
                "next_notes_after": "16th",
                "status": APPLIED,
                "reason": "bar_adds_up",
            },
        )
        self.assertIsNone(block["shared_noteheads"][1]["musicxml_id"])

    def test_the_block_says_when_the_repair_was_off_and_is_absent_when_never_asked(
        self,
    ) -> None:
        lines = [*GRAND_STAFF, "timeSignature/4 . . . . .", *CLEAN_BAR]
        off = StubbedSidecar()
        write(lines, off, repair=False)
        self.assertEqual(
            off.to_json_dict()["timing_repairs"],
            {"version": 1, "enabled": False, "shared_noteheads": []},
        )
        self.assertNotIn("timing_repairs", StubbedSidecar().to_json_dict())


