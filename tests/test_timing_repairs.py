class MeterSidecar(StubbedSidecar):
    """A sidecar whose time-signature reads are scripted, one per token in page order,
    with the meter the previous page ended in."""

    def __init__(
        self,
        scripted: list[tuple[tuple[int, int] | None, str]] | None = None,
        carried: tuple[int, int] | None = None,
        readings: dict[str, SharedNoteheadReading] | None = None,
        symbols: list[str | None] | None = None,
    ) -> None:
        super().__init__(readings)
        reads: Future[tuple[list[Any], list[Any]]] = Future()
        reads.set_result(([], []))
        self.set_time_signature_reads(reads)
        self.set_carried_time_signature(carried)
        self.scripted = list(scripted or [])
        self.symbols = list(symbols or [None] * len(self.scripted))
        self.decided: dict[int, tuple[tuple[int, int] | None, str]] = {}
        self.decided_symbols: dict[int, str | None] = {}

    def _scripted(self, symbol: EncodedSymbol) -> tuple[tuple[int, int] | None, str]:
        if symbol.visual_match_id not in self.decided:
            self.decided[symbol.visual_match_id] = self.scripted.pop(0)
            self.decided_symbols[symbol.visual_match_id] = self.symbols.pop(0)
        return self.decided[symbol.visual_match_id]

    def printed_time_symbol(self, symbol: EncodedSymbol) -> str | None:
        self._scripted(symbol)
        return self.decided_symbols[symbol.visual_match_id]

    def read_time_signature(self, symbol: EncodedSymbol) -> tuple[int, int] | None:
        return self._scripted(symbol)[0]

    def time_signature_status(self, symbol: EncodedSymbol) -> str | None:
        return self._scripted(symbol)[1]


def time_symbols(xml: Any) -> list[str | None]:
    root = ET.fromstring(xml.to_string())  # noqa: S314 - generated by the test itself
    return [t.get("symbol") for t in root.iter("time")]


def written_times(xml: Any) -> list[tuple[str | None, str | None, str | None]]:
    """(beats, beat type, print-object) of every time signature written."""
    root = ET.fromstring(xml.to_string())  # noqa: S314 - generated by the test itself
    return [
        (t.findtext("beats"), t.findtext("beat-type"), t.get("print-object"))
        for t in root.iter("time")
    ]


#: A 2/4 bar of two eighth-note triplets, read as six plain eighths: 3/4 long.
TRIPLET_BAR = ["note_8 E5 _ _ _ upper&note_4 C3 _ _ _ lower", *["note_8 E5 _ _ _ upper"] * 2]
TRIPLET_BAR = [*TRIPLET_BAR, *TRIPLET_BAR, "barline . . . . ."]
TIME_4 = "timeSignature/4 . . . . ."


class TestPrintedTimeSignatures(unittest.TestCase):
    def test_a_read_meter_replaces_the_inferred_one(self) -> None:
        lines = [*GRAND_STAFF, TIME_4, *TRIPLET_BAR, *TRIPLET_BAR]
        self.assertEqual(written_times(write(lines, StubbedSidecar())), [("3", "4", None)])
        sidecar = MeterSidecar([((2, 4), READ)])
        self.assertEqual(written_times(write(lines, sidecar)), [("2", "4", None)])
        self.assertEqual(sidecar.time_signature_at_end(), (2, 4))

    def test_the_carried_meter_is_written_unprinted_where_the_page_has_none(self) -> None:
        lines = [*GRAND_STAFF, *CLEAN_BAR, *CLEAN_BAR]
        sidecar = MeterSidecar(carried=(3, 4))
        self.assertEqual(written_times(write(lines, sidecar)), [("3", "4", "no")])
        self.assertEqual(sidecar.time_signature_at_end(), (3, 4))

    def test_a_page_that_starts_with_a_time_signature_does_not_restate_it(self) -> None:
        lines = [*GRAND_STAFF, TIME_4, *CLEAN_BAR]
        sidecar = MeterSidecar([((2, 4), READ)], carried=(3, 4))
        self.assertEqual(written_times(write(lines, sidecar)), [("2", "4", None)])

    def test_a_token_with_nothing_printed_is_not_written_under_a_trusted_meter(self) -> None:
        lines = [*GRAND_STAFF, *CLEAN_BAR, TIME_4, *TRIPLET_BAR, *TRIPLET_BAR]
        sidecar = MeterSidecar([(None, NO_READ)], carried=(2, 4))
        self.assertEqual(written_times(write(lines, sidecar)), [("2", "4", "no")])
        self.assertEqual(sidecar.time_signature_at_end(), (2, 4))

    def test_without_a_trusted_meter_such_a_token_is_written(self) -> None:
        lines = [*GRAND_STAFF, TIME_4, *TRIPLET_BAR, *TRIPLET_BAR]
        sidecar = MeterSidecar([(None, NO_READ)])
        self.assertEqual(written_times(write(lines, sidecar)), [("3", "4", None)])
        self.assertIsNone(sidecar.time_signature_at_end())

    def test_a_glyph_no_read_could_make_out_ends_the_trusted_meter(self) -> None:
        lines = [*GRAND_STAFF, *CLEAN_BAR, TIME_4, *TRIPLET_BAR, *TRIPLET_BAR]
        for status in (UNREAD_GLYPH, BEAT_TYPE_DIFFERS):
            sidecar = MeterSidecar([(None, status)], carried=(2, 4))
            self.assertEqual(
                written_times(write(lines, sidecar)), [("2", "4", "no"), ("3", "4", None)]
            )
            self.assertIsNone(sidecar.time_signature_at_end())

    def test_a_printed_meter_is_not_replaced_by_what_shared_notehead_repairs_measure(
        self,
    ) -> None:
        # With its repairs the butterfly bar is 2/4, like the clean bar, but the page
        # prints 3/4: the repairs are measured against 3/4 and declined.
        lines = [*GRAND_STAFF, TIME_4, *butterfly_bar("B4", "D5"), *CLEAN_BAR]
        readings = {"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH}
        sidecar = MeterSidecar([((3, 4), READ)], readings=readings)
        xml = write(lines, sidecar)
        self.assertEqual(written_times(xml), [("3", "4", None)])
        self.assertEqual({o[1] for o in outcomes(sidecar)}, {DECLINED})

    def test_shared_notehead_repairs_are_measured_against_the_carried_meter(self) -> None:
        # No time signature, and the only bar is nine 16ths long: the carried 2/4 is
        # what the repair needs.
        bar = butterfly_bar("B4", "D5")
        bar[0] = "note_16 B4 _ _ _ upper&note_8 G2 _ _ _ lower"
        sidecar = MeterSidecar(carried=(2, 4), readings={"D5": EIGHTH_OVER_16TH})
        write([*GRAND_STAFF, *bar], sidecar)
        self.assertEqual(outcomes(sidecar), [("D5", APPLIED, "bar_adds_up", "16th")])

    def test_a_token_left_unwritten_does_not_change_what_repairs_measure(self) -> None:
        # The unprinted token's bars would be measured at 5/8, their length as read.
        lines = [*GRAND_STAFF, "timeSignature/8 . . . . .", *butterfly_bar("B4", "D5")]
        lines += butterfly_bar("B4", "D5")
        readings = {"B4": EIGHTH_OVER_16TH, "D5": EIGHTH_OVER_16TH}
        sidecar = MeterSidecar([(None, NO_READ)], carried=(2, 4), readings=readings)
        xml = write(lines, sidecar)
        self.assertEqual(written_times(xml), [("2", "4", "no")])
        self.assertEqual({o[1] for o in outcomes(sidecar)}, {APPLIED})

    def test_common_and_cut_time_are_written_as_printed(self) -> None:
        lines = [*GRAND_STAFF, TIME_4, *CLEAN_BAR, "timeSignature/2 . . . . .", *CLEAN_BAR]
        sidecar = MeterSidecar([((4, 4), READ), ((2, 2), READ)], symbols=["common", "cut"])
        xml = write(lines, sidecar)
        self.assertEqual(written_times(xml), [("4", "4", None), ("2", "2", None)])
        self.assertEqual(time_symbols(xml), ["common", "cut"])

    def test_numbers_and_unprinted_meters_get_no_symbol(self) -> None:
        lines = [*GRAND_STAFF, *CLEAN_BAR, TIME_4, *CLEAN_BAR]
        sidecar = MeterSidecar([((4, 4), READ)], carried=(4, 4))
        xml = write(lines, sidecar)
        self.assertEqual(written_times(xml), [("4", "4", "no"), ("4", "4", None)])
        self.assertEqual(time_symbols(xml), [None, None])

    def test_without_reads_the_writer_infers_every_meter(self) -> None:
        lines = [*GRAND_STAFF, TIME_4, *TRIPLET_BAR, *TRIPLET_BAR]
        sidecar = StubbedSidecar()
        self.assertEqual(written_times(write(lines, sidecar)), [("3", "4", None)])
        self.assertIsNone(sidecar.time_signature_at_end())
        self.assertNotIn("time_signatures", sidecar.to_json_dict())


