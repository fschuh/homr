    return VisualGroup(
        visual_id=visual_id,
        staff_group_index=0,
        staff_index=0,
        staff_position=0,
        prediction_center=(200.0, 130.0),
        prediction_notehead_size=(26.0, 18.0),
        transformer_center=None,
        transformer_notehead_size=None,
        notehead_ellipses=[],
        notehead_contours=[],
        detected_notehead_contours=[],
        refined_notehead_contours=[],
        detected_stem_contours=[],
        stem_contours=[],
        owned_stem_component_ids=[],
        is_hollow_notehead=False,
        visual_status="canonical",
        provenance="test",
    )
